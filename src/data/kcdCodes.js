export function searchKCD(query) {
  if (!query || query.length < 1) return []
  const q = query.toLowerCase().replace(/\s/g, '')
  return KCD_CODES.filter(k =>
    k.code.toLowerCase().startsWith(q) ||
    k.name.replace(/\s/g, '').toLowerCase().includes(q) ||
    k.cat.includes(query)
  ).slice(0, 10)
}
