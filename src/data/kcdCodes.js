// 검색 함수 — 코드 또는 이름으로 검색 (최대 20개)
export function searchKCD(q) {
  if (!q || q.length < 1) return []
  const s = q.toLowerCase().replace(/\s/g, '')
  return KCD_CODES.filter(item =>
    item.code.toLowerCase().startsWith(s) ||
    item.name.replace(/\s/g, '').toLowerCase().includes(s) ||
    item.code.toLowerCase().includes(s)
  ).slice(0, 20)
}
